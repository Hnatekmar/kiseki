package cli

import (
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"

	"forgejo.srv.hnatekmar.dev/hnatekmar/kiseki/internal/repo"
)

// exampleYAML is the canonical sidecar example. It lives here rather than in a
// separate file so the generator, examples/extraSVC.yaml and the docs cannot
// drift: just lint diffs the output against the committed file.
const exampleYAML = `# Sidecars for a dev environment. Generated by ` + "`" + `kiseki example` + "`" + `.
#
#   kiseki create api -f extraSVC.yaml \
#     --address api.dev-k8s.srv.hnatekmar.dev --port 8080
#
# Every container in the pod shares one network namespace, so the dev container
# reaches these on 127.0.0.1. Ports declared under extraContainers are waited on
# before sshd starts, which removes the startup race with redis or postgres.

# Volumes exist for the whole pod. A sidecar mounts them through its own
# volumeMounts; the dev container needs an extraVolumeMounts entry.
extraVolumes:
  - name: pgdata
    emptyDir: {}          # replace with persistentVolumeClaim to survive restarts
  - name: seed
    emptyDir: {}

extraVolumeMounts:
  - name: seed
    mountPath: /seed
    readOnly: true

# Run to completion before the dev container and the sidecars start.
extraInitContainers:
  - name: seed
    image: busybox:1.36
    command:
      - sh
      - -c
      - echo "hello from the init container" > /seed/hello.txt
    volumeMounts:
      - name: seed
        mountPath: /seed

extraContainers:
  - name: redis
    image: redis:7-alpine
    ports:
      - name: redis
        containerPort: 6379
    resources:
      requests: {cpu: 50m, memory: 64Mi}
      limits: {cpu: 500m, memory: 256Mi}
    readinessProbe:
      tcpSocket: {port: 6379}
      periodSeconds: 2

  - name: postgres
    image: postgres:17-alpine
    ports:
      - name: postgres
        containerPort: 5432
    env:
      - name: POSTGRES_USER
        value: dev
      - name: POSTGRES_PASSWORD
        value: dev
      - name: POSTGRES_DB
        value: app
    volumeMounts:
      - name: pgdata
        mountPath: /var/lib/postgresql/data
    resources:
      requests: {cpu: 100m, memory: 128Mi}
      limits: {cpu: "1", memory: 512Mi}
    readinessProbe:
      exec:
        # -d matters: pg_isready defaults to a database named after the user,
        # and a missing one logs FATAL on every probe.
        command: ["pg_isready", "-U", "dev", "-d", "app"]
      periodSeconds: 2
`

func runExample(args []string, out, errw io.Writer) int {
	path := ""
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "-o", "--output":
			if i+1 >= len(args) {
				fmt.Fprintln(errw, "kiseki: --output needs a path")
				return 1
			}
			path = args[i+1]
			i++
		case "-h", "--help":
			fmt.Fprintf(out, "usage: kiseki example [--output FILE]\n")
			return 0
		default:
			fmt.Fprintf(errw, "kiseki: Unknown argument: %s\n", args[i])
			return 1
		}
	}

	if path == "" {
		fmt.Fprint(out, exampleYAML)
		return 0
	}

	if dir := filepath.Dir(path); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fmt.Fprintf(errw, "kiseki: %v\n", err)
			return 1
		}
	}
	if err := os.WriteFile(path, []byte(exampleYAML), 0o644); err != nil {
		fmt.Fprintf(errw, "kiseki: %v\n", err)
		return 1
	}

	// Render the file against the real chart: a sample that does not template is
	// worse than no sample.
	if _, err := exec.LookPath("helm"); err == nil {
		chart, err := repo.ChartDir()
		if err != nil {
			fmt.Fprintf(errw, "kiseki: %v\n", err)
			return 1
		}
		cmd := exec.Command("helm", "template", "kiseki-example", chart,
			"--set", "ssh.authorizedKey=example", "-f", path)
		cmd.Stdout, cmd.Stderr = io.Discard, errw
		if err := cmd.Run(); err != nil {
			fmt.Fprintf(errw, "kiseki: generated file does not render: %s\n", path)
			return 1
		}
	}

	fmt.Fprintf(out, "Wrote %s\n", path)
	fmt.Fprintf(out, "Use it with: kiseki create <name> -f %s\n", path)
	return 0
}
